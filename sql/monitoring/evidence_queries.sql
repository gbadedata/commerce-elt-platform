-- Run each block on its own in Snowsight, and screenshot the result for the README.

-- 1. Row counts loaded into RAW.
USE ROLE TRANSFORMER_ROLE;
USE WAREHOUSE TRANSFORM_WH;
SELECT 'customers' AS entity, COUNT(*) AS raw_rows FROM COMMERCE_DB.RAW.CUSTOMERS
UNION ALL SELECT 'products', COUNT(*) FROM COMMERCE_DB.RAW.PRODUCTS
UNION ALL SELECT 'orders', COUNT(*) FROM COMMERCE_DB.RAW.ORDERS
UNION ALL SELECT 'order_items', COUNT(*) FROM COMMERCE_DB.RAW.ORDER_ITEMS;

-- 2. Latest result for every rule.
USE ROLE TRANSFORMER_ROLE;
USE WAREHOUSE TRANSFORM_WH;
SELECT RULE_ID, DIMENSION, DQ_SEVERITY, OWNER, STATUS, FAILED_ROWS, ROWS_CHECKED, PASS_RATE
FROM COMMERCE_DB.MONITORING.V_DQ_LATEST
ORDER BY STATUS, DQ_SEVERITY, RULE_ID;

-- 3. Quarantine by reason.
USE ROLE TRANSFORMER_ROLE;
USE WAREHOUSE TRANSFORM_WH;
SELECT ENTITY, REJECT_REASON, COUNT(*) AS ROWS_REJECTED
FROM COMMERCE_DB.MONITORING.QUARANTINE_ROWS
GROUP BY ENTITY, REJECT_REASON
ORDER BY ENTITY, REJECT_REASON;

-- 4. The reporting role can read marts. Secondary roles must be off, or your
-- other roles stay active and this says nothing about REPORTER_ROLE.
USE ROLE REPORTER_ROLE;
USE SECONDARY ROLES NONE;
USE WAREHOUSE TRANSFORM_WH;
SELECT COUNT(*) AS MART_ROWS, SUM(NET_AMOUNT) AS NET_VALUE FROM COMMERCE_DB.MARTS.FCT_ORDER_ITEMS;

-- 5. The reporting role cannot read staging, where personal data lives.
-- This should fail with an access error. That error is the evidence.
USE ROLE REPORTER_ROLE;
USE SECONDARY ROLES NONE;
USE WAREHOUSE TRANSFORM_WH;
SELECT EMAIL FROM COMMERCE_DB.STAGING.STG_CUSTOMERS LIMIT 1;
