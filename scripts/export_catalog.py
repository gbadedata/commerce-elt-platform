"""Write docs/data_catalog.md from dbt metadata: owners, definitions, personal data, lineage and rules."""

from __future__ import annotations

import json
import sys

import warehouse
import yaml

TARGET = warehouse.ROOT / "commerce_dbt" / "target"
DOCS = warehouse.ROOT / "docs"


def short(node_id: str) -> str:
    parts = node_id.split(".")
    return f"{parts[-2]}.{parts[-1]}" if node_id.startswith("source.") else parts[-1]


def main() -> int:
    manifest = json.loads((TARGET / "manifest.json").read_text())
    glossary = yaml.safe_load((warehouse.ROOT / "governance" / "business_glossary.yml").read_text())
    models = {k: v for k, v in manifest["nodes"].items() if v["resource_type"] == "model"}
    rules_by_model: dict[str, list[str]] = {}
    for node in manifest["nodes"].values():
        rule = (node.get("config", {}).get("meta") or {}).get("rule_id")
        if node["resource_type"] == "test" and rule and node.get("attached_node"):
            rules_by_model.setdefault(node["attached_node"], []).append(rule)

    lines = ["# Data catalog", "", "Generated by `scripts/export_catalog.py` from dbt metadata. Do not edit by hand.", ""]
    lines += ["## Business glossary", "", "| Term | Definition | Owner | Location |", "|---|---|---|---|"]
    for term in glossary["terms"]:
        lines.append(f"| {term['term']} | {term['definition']} | {term['owner']} | `{term['location']}` |")

    lines += ["", "## Lineage", "", "```mermaid", "flowchart LR"]
    for _, node in sorted(models.items()):
        for parent in node["depends_on"]["nodes"]:
            lines.append(f"    {short(parent).replace('.', '_')} --> {node['name']}")
    lines += ["```", "", "## Models", ""]

    order = {"marts": 0, "monitoring": 1, "intermediate": 2, "staging": 3}
    for node_id, node in sorted(models.items(), key=lambda kv: (order.get(kv[1]["schema"].lower(), 9), kv[1]["name"])):
        meta = node["config"].get("meta") or {}
        upstream = ", ".join(f"`{short(p)}`" for p in node["depends_on"]["nodes"]) or "none"
        downstream = sorted(short(c) for c in manifest["child_map"].get(node_id, []) if c.startswith("model."))
        lines += [
            f"### {node['name']}",
            "",
            node.get("description", ""),
            "",
            f"- **Schema:** {node['schema']}",
            f"- **Owner:** {meta.get('owner', 'UNASSIGNED')}",
            f"- **Grain:** {meta.get('grain', 'not stated')}",
            f"- **Contains personal data:** {'yes' if meta.get('contains_pii') else 'no'}",
            f"- **Upstream:** {upstream}",
            f"- **Downstream:** {', '.join(f'`{d}`' for d in downstream) or 'none'}",
        ]
        if meta.get("consumers"):
            lines.append(f"- **Consumers:** {', '.join(meta['consumers'])}")
        rules = sorted(rules_by_model.get(node_id, []))
        if rules:
            lines.append(f"- **Rules:** {', '.join(f'`{r}`' for r in rules)}")
        documented = [c for c in node["columns"].values() if c.get("description")]
        if documented:
            lines += ["", "| Column | Description | Personal data |", "|---|---|---|"]
            for col in documented:
                pii = "yes" if (col.get("meta") or col.get("config", {}).get("meta") or {}).get("pii") else ""
                lines.append(f"| `{col['name']}` | {col['description']} | {pii} |")
        lines.append("")

    DOCS.mkdir(exist_ok=True)
    (DOCS / "data_catalog.md").write_text("\n".join(lines))
    print(f"Wrote {DOCS / 'data_catalog.md'} with {len(models)} models")
    return 0


if __name__ == "__main__":
    sys.exit(main())
